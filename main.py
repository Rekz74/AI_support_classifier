df = pd.DataFrame(data, columns=["text", "category", "priority"])

print("Количество обращений:", len(df))
print("\nРаспределение по категориям:")
print(df["category"].value_counts())

X = df["text"]
y_category = df["category"]
y_priority = df["priority"]

X_train, X_test, y_category_train, y_category_test, y_priority_train, y_priority_test = train_test_split(
    X,
    y_category,
    y_priority,
    test_size=0.25,
    random_state=42,
    stratify=y_category
)

category_model = Pipeline([
    ("tfidf", TfidfVectorizer()),
    ("classifier", LogisticRegression(max_iter=1000))
])

priority_model = Pipeline([
    ("tfidf", TfidfVectorizer()),
    ("classifier", LogisticRegression(max_iter=1000))
])

category_model.fit(X_train, y_category_train)
priority_model.fit(X_train, y_priority_train)
category_pred = category_model.predict(X_test)
priority_pred = priority_model.predict(X_test)
category_accuracy = accuracy_score(y_category_test, category_pred)
priority_accuracy = accuracy_score(y_priority_test, priority_pred)

print("\nРезультаты проверки:")
print(f"Точность определения категории: {category_accuracy:.2%}")
print(f"Точность определения приоритета: {priority_accuracy:.2%}")
print("\nОтчет по категориям:")
print(classification_report(y_category_test, category_pred, zero_division=0))
print("Отчет по приоритетам:")
print(classification_report(y_priority_test, priority_pred, zero_division=0))

def predict_ticket(text):
    category = category_model.predict([text])[0]
    priority = priority_model.predict([text])[0]

    print("\nРезультат анализа:")
    print("Категория:", category)
    print("Приоритет:", priority)

